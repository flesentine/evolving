import Foundation
import Metal
import MetalKit

enum MetalSetupError: Error, CustomStringConvertible {
    case noDevice
    case noCommandQueue
    case noShaderSource
    case shaderCompilation(String)
    case pipeline(String)
    case buffer(String)

    var description: String {
        switch self {
        case .noDevice:              return "Metal is not available on this machine."
        case .noCommandQueue:        return "Could not create a Metal command queue."
        case .noShaderSource:        return "No shader source was embedded in this build."
        case .shaderCompilation(let m): return "Metal shader compilation failed:\n\(m)"
        case .pipeline(let m):       return "Render pipeline creation failed: \(m)"
        case .buffer(let m):         return "Buffer allocation failed: \(m)"
        }
    }
}

/// Owns the Metal device, command queue and compiled shader library.
///
/// Shaders are compiled at runtime from the source generated by `build.sh`.
/// That keeps the `.saver` bundle free of resource lookups and removes the
/// dependency on the (optional) Xcode Metal toolchain.
final class MetalContext {
    let device: MTLDevice
    let queue: MTLCommandQueue
    let library: MTLLibrary

    init() throws {
        guard let device = MTLCreateSystemDefaultDevice() else { throw MetalSetupError.noDevice }
        guard let queue = device.makeCommandQueue() else { throw MetalSetupError.noCommandQueue }

        guard let source = EvolvingShaderSource.source, !source.isEmpty else {
            throw MetalSetupError.noShaderSource
        }

        let options = MTLCompileOptions()
        options.fastMathEnabled = true

        do {
            self.library = try device.makeLibrary(source: source, options: options)
        } catch {
            throw MetalSetupError.shaderCompilation(String(describing: error))
        }

        self.device = device
        self.queue = queue
    }

    func makeFunction(_ name: String) throws -> MTLFunction {
        guard let fn = library.makeFunction(name: name) else {
            throw MetalSetupError.pipeline("missing shader function '\(name)'")
        }
        return fn
    }
}
