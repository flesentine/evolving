#!/bin/bash
# Builds the Evolving screen saver bundle and the headless development tool.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

BUILD="$ROOT/build"
BUNDLE="$BUILD/Evolving.saver"
BIN="$BUILD/bin"
GEN="$BUILD/gen"
OBJ="$BUILD/obj"
SDK="macosx"
TARGET="arm64-apple-macos13.0"
SWIFT_VERSION="5"

FRAMEWORKS=(
  -framework AppKit
  -framework ScreenSaver
  -framework Metal
  -framework MetalKit
  -framework QuartzCore
  -framework CoreGraphics
  -framework ImageIO
)

SWIFT_RUNTIME_PATHS=(
  -L "$(xcrun --find swiftc | xargs dirname)/../lib/swift/macosx"
  -L /usr/lib/swift
)

rm -rf "$BUILD"
mkdir -p "$BUNDLE/Contents/MacOS" "$BUNDLE/Contents/Resources" "$BIN" "$GEN" "$OBJ"

# ---------------------------------------------------------------------------
# Shaders
#
# The Xcode Metal toolchain is an optional download, so shaders are embedded as
# a Swift string and compiled by the GPU driver at startup instead. The .metal
# files remain the source of truth.
# ---------------------------------------------------------------------------
echo "▸ embedding shaders"
{
  echo "// Generated by Scripts/build.sh — do not edit."
  echo "// Source of truth: Sources/CivRender/*.metal"
  echo "import Foundation"
  echo ""
  echo "enum EvolvingShaderSource {"
  echo "    static let source: String? = #\"\"\""
  cat Sources/CivRender/*.metal
  echo ""
  echo "\"\"\"#"
  echo "}"
} > "$GEN/GeneratedShaderSource.swift"

# ---------------------------------------------------------------------------
# Sources
# ---------------------------------------------------------------------------
RENDER_SOURCES=()
while IFS= read -r -d '' file; do
  RENDER_SOURCES+=("$file")
done < <(find Sources/CivCore Sources/CivRender -name '*.swift' -print0 | sort -z)

# ---------------------------------------------------------------------------
# Screen saver
#
# A .saver executable is a loadable Mach-O bundle, not an executable, so it is
# compiled to an object file and linked with -bundle explicitly.
# ---------------------------------------------------------------------------
echo "▸ compiling screen saver"
xcrun -sdk "$SDK" swiftc \
  -emit-object \
  -whole-module-optimization \
  -parse-as-library \
  -target "$TARGET" \
  -swift-version "$SWIFT_VERSION" \
  -O \
  -module-name Evolving \
  "${RENDER_SOURCES[@]}" \
  "$GEN/GeneratedShaderSource.swift" \
  Sources/Saver/EvolvingSaver.swift \
  -o "$OBJ/Evolving.o"

echo "▸ linking bundle"
clang -bundle \
  -target "$TARGET" \
  -o "$BUNDLE/Contents/MacOS/Evolving" \
  "$OBJ/Evolving.o" \
  "${SWIFT_RUNTIME_PATHS[@]}" \
  "${FRAMEWORKS[@]}" \
  -Wl,-rpath,/usr/lib/swift

cp Saver/Info.plist "$BUNDLE/Contents/Info.plist"
printf 'APPL????' > "$BUNDLE/Contents/PkgInfo"

# Imported hero assets.
echo "▸ bundling assets"
mkdir -p "$BUNDLE/Contents/Resources/Assets/Buildings/variants"
cp Assets/Buildings/*.civmesh \
   Assets/Buildings/buildings-atlas.png \
   "$BUNDLE/Contents/Resources/Assets/Buildings/"
cp Assets/Buildings/variants/*.civmesh \
   "$BUNDLE/Contents/Resources/Assets/Buildings/variants/"
mkdir -p "$BUNDLE/Contents/Resources/Assets/Terrain"
cp Assets/Terrain/*.png \
   "$BUNDLE/Contents/Resources/Assets/Terrain/"
mkdir -p "$BUNDLE/Contents/Resources/Assets/Roads"
cp Assets/Roads/*.png \
   "$BUNDLE/Contents/Resources/Assets/Roads/"

# Sign with a Developer ID when one is available (required for notarization),
# otherwise fall back to an ad-hoc signature so local builds still load.
SIGN_IDENTITY="${EVOLVING_SIGN_IDENTITY:-}"
if [[ -z "$SIGN_IDENTITY" ]]; then
  # CI macOS runners generally have no Developer ID identity. Under
  # "set -euo pipefail" an empty grep result otherwise aborts the build
  # before the intended ad-hoc signing fallback can run.
  SIGN_IDENTITY=$(security find-identity -v -p codesigning 2>/dev/null \
    | grep "Developer ID Application" | head -1 | sed -E 's/.*"(.*)"/\1/' || true)
fi

sign_bundle() {
  local target="$1"
  if [[ -n "$SIGN_IDENTITY" ]]; then
    codesign --force --options runtime --timestamp --sign "$SIGN_IDENTITY" "$target" 2>/dev/null \
      || codesign --force --options runtime --sign "$SIGN_IDENTITY" "$target"
  else
    codesign --force --sign - "$target"
  fi
}

echo "▸ signing"
if [[ -n "$SIGN_IDENTITY" ]]; then
  echo "  identity: $SIGN_IDENTITY"
else
  echo "  ad hoc (no Developer ID identity found)"
fi
if sign_bundle "$BUNDLE" >/dev/null 2>&1; then
  echo "  saver signed"
else
  echo "  saver signing failed, leaving unsigned"
fi

# ---------------------------------------------------------------------------
# Headless tool
# ---------------------------------------------------------------------------
echo "▸ compiling headless tool"
HEADLESS_SOURCES=()
while IFS= read -r -d '' file; do
  HEADLESS_SOURCES+=("$file")
done < <(find Sources/Headless -name '*.swift' -print0 | sort -z)

xcrun -sdk "$SDK" swiftc \
  -target "$TARGET" \
  -swift-version "$SWIFT_VERSION" \
  -O \
  -module-name CivHeadless \
  "${RENDER_SOURCES[@]}" \
  "$GEN/GeneratedShaderSource.swift" \
  "${HEADLESS_SOURCES[@]}" \
  "${FRAMEWORKS[@]}" \
  -o "$BIN/civheadless"

# ---------------------------------------------------------------------------
# Companion app
#
# A tiny AppKit window that reads the same defaults domain and shows the world
# state. It only needs CivCore, so it does not pull in Metal.
# ---------------------------------------------------------------------------
echo "▸ compiling companion app"
APP="$BUILD/Evolving Companion.app"
mkdir -p "$APP/Contents/MacOS"

CORE_SOURCES=()
while IFS= read -r -d '' file; do
  CORE_SOURCES+=("$file")
done < <(find Sources/CivCore -name '*.swift' -print0 | sort -z)

xcrun -sdk "$SDK" swiftc \
  -target "$TARGET" \
  -swift-version "$SWIFT_VERSION" \
  -O \
  -module-name EvolvingCompanion \
  "${CORE_SOURCES[@]}" \
  Sources/Companion/main.swift \
  -framework AppKit \
  -framework ScreenSaver \
  -o "$APP/Contents/MacOS/EvolvingCompanion"

cp Companion/Info.plist "$APP/Contents/Info.plist"
printf 'APPL????' > "$APP/Contents/PkgInfo"

if sign_bundle "$APP" >/dev/null 2>&1; then
  echo "  companion signed"
else
  echo "  companion signing failed, leaving unsigned"
fi

# ---------------------------------------------------------------------------
# Player app
#
# A standalone full-screen host for the saver bundle, so the world can be
# launched without going through System Settings.
# ---------------------------------------------------------------------------
echo "▸ compiling player app"
PLAYER="$BUILD/Evolving Player.app"
mkdir -p "$PLAYER/Contents/MacOS" "$PLAYER/Contents/Resources"
cp -R "$BUNDLE" "$PLAYER/Contents/Resources/Evolving.saver"

xcrun -sdk "$SDK" swiftc \
  -target "$TARGET" \
  -swift-version "$SWIFT_VERSION" \
  -O \
  -module-name EvolvingPlayer \
  Sources/Player/main.swift \
  -framework AppKit \
  -framework ScreenSaver \
  -o "$PLAYER/Contents/MacOS/EvolvingPlayer"

cp Player/Info.plist "$PLAYER/Contents/Info.plist"
printf 'APPL????' > "$PLAYER/Contents/PkgInfo"

if sign_bundle "$PLAYER" >/dev/null 2>&1; then
  echo "  player signed"
else
  echo "  player signing failed, leaving unsigned"
fi

# ---------------------------------------------------------------------------
# Timeline app
#
# Standalone viewer with a year slider, so the whole arc can be scrubbed
# without going through Screen Saver settings.
# ---------------------------------------------------------------------------
echo "▸ compiling timeline app"
TIMELINE="$BUILD/Evolving Timeline.app"
mkdir -p "$TIMELINE/Contents/MacOS" "$TIMELINE/Contents/Resources"
cp -R "$BUNDLE" "$TIMELINE/Contents/Resources/Evolving.saver"

xcrun -sdk "$SDK" swiftc \
  -target "$TARGET" \
  -swift-version "$SWIFT_VERSION" \
  -O \
  -module-name EvolvingTimeline \
  "${CORE_SOURCES[@]}" \
  Sources/Timeline/main.swift \
  -framework AppKit \
  -framework ScreenSaver \
  -o "$TIMELINE/Contents/MacOS/EvolvingTimeline"

cp Timeline/Info.plist "$TIMELINE/Contents/Info.plist"
printf 'APPL????' > "$TIMELINE/Contents/PkgInfo"

if sign_bundle "$TIMELINE" >/dev/null 2>&1; then
  echo "  timeline signed"
else
  echo "  timeline signing failed, leaving unsigned"
fi

echo "▸ done"
echo "  bundle: $BUNDLE"
echo "  tool:   $BIN/civheadless"
echo "  app:    $APP"
echo "  player: $PLAYER"
echo "  timeline: $TIMELINE"
